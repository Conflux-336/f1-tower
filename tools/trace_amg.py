#!/usr/bin/env python3
"""Trace the AMG wordmark (speed slashes + A M G) from the official PNG into
filled polygons, emit f1tower/amgmark.h, and render a preview."""
import os

import cv2
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "f1tower")
SRC = ("/Users/aespa/.qoder/tmp/-Users-aespa-Documents-Qoder-2026-11-08-9960d41b/"
       "images/9960d41b-4f8f-4bd5-b04b-9dae63d38dd5/"
       "2908c615-5178-493e-9857-aa930d9c7311.png")

X0, X1 = 105, 440          # ink bounds of the lockup
Y0, Y1 = 312, 346          # AMG band
UP = 8                     # upscale before tracing

img = cv2.imread(SRC, cv2.IMREAD_COLOR)
g = img.max(axis=2)
band = g[Y0:Y1, X0:X1].astype(np.float32) / 255.0
big = cv2.resize(band, None, fx=UP, fy=UP, interpolation=cv2.INTER_CUBIC)
mask = (big > 0.5).astype(np.uint8) * 255
# light close to heal single-pixel notches from the source AA
mask = cv2.morphologyEx(mask, cv2.MORPH_CLOSE, np.ones((3, 3), np.uint8))

contours, hierarchy = cv2.findContours(mask, cv2.RETR_CCOMP,
                                       cv2.CHAIN_APPROX_SIMPLE)
polys = []
for i, c in enumerate(contours):
    area = cv2.contourArea(c) / (UP * UP)
    if area < 1.0:                       # drop AA specks
        continue
    eps = 1.2                            # 8x space -> 0.15 source px
    ap = cv2.approxPolyDP(c, eps, True).reshape(-1, 2).astype(np.float32)
    ap = ap / UP                         # back to mark pixels
    polys.append((i, hierarchy[0][i][3], area, ap))

polys.sort(key=lambda p: -p[2])
print(f"{len(polys)} contours, {sum(len(p[3]) for p in polys)} points")

# ---- C header -------------------------------------------------------------
W = float(X1 - X0)
H = float(Y1 - Y0)
lines = ["// generated by tools/trace_amg.py from the official mark - do not edit",
         "#pragma once", "#include <stdint.h>", "",
         f"constexpr int AMG_W = {int(W)};", f"constexpr int AMG_H = {int(H)};", "",
         "// ring order: outer boundary, then its holes"]
pts_all = []
entries = []
for idx, parent, area, ap in polys:
    first = len(pts_all) // 2
    for x, y in ap:
        pts_all.append(int(round(x)))
        pts_all.append(int(round(y)))
    entries.append((first, len(ap), parent))

lines.append(f"static const int16_t AMG_PTS[] = {{")
for i in range(0, len(pts_all), 16):
    lines.append("  " + ",".join(str(v) for v in pts_all[i:i + 16]) + ",")
lines.append("};")
lines.append("")
lines.append("struct AmgPoly { uint16_t first; uint8_t n; uint8_t pad; };")
lines.append("static const AmgPoly AMG_POLYS[] = {")
for first, n, parent in entries:
    lines.append(f"  {{{first},{n},0}},")
lines.append("};")
lines.append(f"constexpr int AMG_POLY_COUNT = {len(entries)};")
open(os.path.join(OUT, "amgmark.h"), "w").write("\n".join(lines) + "\n")

# ---- preview at a few sizes ----------------------------------------------
from PIL import Image, ImageDraw

def render(width):
    s = width / W
    h = int(round(H * s))
    im = Image.new("L", (width, h), 0)
    d = ImageDraw.Draw(im)
    for idx, parent, area, ap in polys:
        d.polygon([(float(x) * s, float(y) * s) for x, y in ap], fill=255)
    return im

import json
with open(os.path.join(HERE, "amgmark_polys.json"), "w") as fh:
    json.dump([[list(map(float, p)) for p in ap] for _, _, _, ap in polys], fh)

out = Image.new("RGB", (720, 200), (13, 13, 13))
x = 20
for w in (140, 300, 600):
    r = render(w)
    out.paste((255, 255, 255), (x, 30), r)
    x += w + 20
out.save(os.path.join(HERE, "amgmark_preview.png"))
print("wrote amgmark.h and amgmark_preview.png")
