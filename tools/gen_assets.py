#!/usr/bin/env python3
"""Generate bitmap font atlases + three-pointed-star masks for the F1 display."""
import math
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(os.path.dirname(HERE), "f1tower")

FONT_PATH = "/System/Library/Fonts/Supplemental/Arial Bold.ttf"
CHARS = [chr(c) for c in range(32, 127)] + ["°", "·", "–"]
SIZES = {"10": 10, "12": 12, "16": 16, "22": 22, "28": 28}

SS = 4  # supersample factor for masks


def build_font(px):
    font = ImageFont.truetype(FONT_PATH, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    blob = bytearray()
    for ch in CHARS:
        adv = int(round(font.getlength(ch)))
        canvas = Image.new("L", (px * 3, px * 3), 0)
        d = ImageDraw.Draw(canvas)
        base = px * 2
        d.text((px, base), ch, font=font, fill=255, anchor="ls")
        bbox = canvas.getbbox()
        if not bbox:
            glyphs.append((ord(ch), 0, 0, 0, 0, adv, len(blob)))
            continue
        x0, y0, x1, y1 = bbox
        # align to the baseline used during rasterisation (base)
        top = y0 - base
        left = x0 - px
        w, h = x1 - x0, y1 - y0
        crop = canvas.crop(bbox)
        glyphs.append((ord(ch), w, h, left, top, adv, len(blob)))
        blob.extend(crop.tobytes())
    return ascent, descent, glyphs, bytes(blob)


def emit_font(name, px):
    ascent, descent, glyphs, blob = build_font(px)
    lines = []
    lines.append("// generated by tools/gen_assets.py - do not edit")
    lines.append(f"static const uint8_t font{name}_alpha[] PROGMEM = {{")
    for i in range(0, len(blob), 24):
        lines.append("  " + ",".join(str(b) for b in blob[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const Glyph font{name}_glyphs[] PROGMEM = {{")
    for (cp, w, h, xo, yo, adv, off) in glyphs:
        lines.append(f"  {{0x{cp:04X},{w},{h},{xo},{yo},{adv},{off}}},")
    lines.append("};")
    lines.append(
        f"static const BitmapFont font{name} = {{font{name}_glyphs, font{name}_alpha, "
        f"{len(glyphs)}, {ascent}, {descent}}};"
    )
    return "\n".join(lines)


def star_mask(size):
    """Three-pointed star inside a ring, supersampled then downscaled.

    Arm cross-section follows the real mark: wide at the hub, tapering to a
    narrow tip at the ring (measured: notch r=16.6 @ 60deg, tip half-width
    3.9 @ r=91, ring band 91..100 for R=100).
    """
    big = size * SS
    img = Image.new("L", (big, big), 0)
    d = ImageDraw.Draw(img)
    cx = cy = big / 2.0
    r_out = big / 2.0 - SS
    ring_w = max(1.6 * SS, r_out * 0.09)
    d.ellipse([cx - r_out, cy - r_out, cx + r_out, cy + r_out],
              outline=255, width=int(round(ring_w)))
    r_tip = r_out * 0.91
    r_notch, a_notch = r_out * 0.166, math.radians(60)
    half_tip = r_tip * 0.043

    for deg in (90, 210, 330):
        a = math.radians(deg)
        sa, ca = math.sin(a), math.cos(a)

        # arm-local (px across, py along) -> screen, arm pointing at `deg`
        def rot(px, py):
            return (cx + px * sa + py * ca, cy + px * ca - py * sa)

        nx, ny = r_notch * math.sin(a_notch), r_notch * math.cos(a_notch)
        pts = [(cx, cy), rot(nx, ny), rot(half_tip, r_tip),
               rot(-half_tip, r_tip), rot(-nx, ny)]
        d.polygon(pts, fill=255)
    img = img.resize((size, size), Image.LANCZOS)
    return img


def pack4(img):
    w, h = img.size
    out = bytearray()
    px = img.load()
    for y in range(h):
        for x in range(0, w, 2):
            hi = px[x, y] >> 4
            lo = px[x + 1, y] >> 4 if x + 1 < w else 0
            out.append((hi << 4) | lo)
    return bytes(out)


def emit_star(name, img):
    w, h = img.size
    data = pack4(img)
    lines = [f"static const uint8_t {name}_alpha[] PROGMEM = {{"]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const StarMask {name} = {{{w},{h},{name}_alpha}};")
    return "\n".join(lines)


def main():
    fonts = "\n\n".join(emit_font(n, px) for n, px in SIZES.items())
    preview = {}
    stars = []
    for s in (20, 44, 120):
        img = star_mask(s)
        preview[s] = img
        stars.append(emit_star(f"star{s}", img))

    header = f"""// generated by tools/gen_assets.py - do not edit
#pragma once
#include <stdint.h>

{fonts}

{chr(10).join(stars)}
"""
    with open(os.path.join(OUT, "assets.h"), "w") as f:
        f.write(header)

    for s, img in preview.items():
        img.save(os.path.join(HERE, f"star_{s}.png"))

    # contact sheet on a dark panel so it reads like the real screen
    sheet = Image.new("RGB", (300, 140), (13, 13, 13))
    for i, (s, img) in enumerate(preview.items()):
        tint = Image.new("RGB", img.size, (0, 215, 182))
        sheet.paste(tint, (10 + i * 100 + (100 - s) // 2, 10 + (100 - s) // 2), img)
    font16 = ImageFont.truetype(FONT_PATH, 16)
    d = ImageDraw.Draw(sheet)
    d.text((10, 112), "AMG PETRONAS  ·  LAP 32/71", font=font16, fill=(200, 200, 200))
    sheet.save(os.path.join(HERE, "preview.png"))
    print("wrote assets.h and previews")


if __name__ == "__main__":
    main()
